"""Extract the units of measure from the XWaermeplan feature catalogue.

The XSD types every measure as ``gml:MeasureType`` without a unit; the units
are only in the feature catalogue (Objektartenkatalog) of the XLeitstelle, a
ZIP of HTML pages generated by ShapeChange. This script writes them as
``{class: {attribute: unit}}`` to the test fixture that
``tests/test_xwp_evidence.py`` compares the units in ``mapping.CLASSES`` against.

Only the packages of the current model count; the ZIP also carries pages of
outdated packages (e.g. ``WP_Fachobjekte``, ``WP_Objekte``) with other units.

    python scripts/extract_xwp_units.py <spezifikation>/objektartenkatalog/XWaermeplan096.zip \
        tests/fixtures/xwp/oak-0.9.6-einheiten.json
"""
from __future__ import annotations

import argparse
import hashlib
import html
import json
import re
import sys
import zipfile
from pathlib import Path

PACKAGES = ("WP_Basisobjekte", "WP_Raumobjekte", "WP_Reporting")

_TITLE = re.compile(r"<h1[^>]*>(.*?)</h1>", re.S)
_PROPERTY = re.compile(r'<h2 class="\w+Property"><a name="[^"]*">(?:Attribut|Assoziationsrolle): (\w+)</a></h2>')
# "Maßeinheit" is spelled with a broken ß on some pages, so only the end is matched
_UNIT = re.compile(r'einheit: </p>\s*</td>\s*<td>\s*<p>(.*?)</p>', re.S)
#: Units whose characters the catalogue lost (U+FFFD in the published pages)
REPAIRS = {"�C": "°C"}


def git_blob(data: bytes) -> str:
    """Git object id of a file's content, to name the exact source in the fixture."""
    return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()


def decode(raw: bytes) -> str:
    try:
        return raw.decode("utf-8")
    except UnicodeDecodeError:  # some pages are Windows-1252 despite their meta tag
        return raw.decode("cp1252")


def page_units(text: str) -> tuple[str, dict[str, str]]:
    """Class name and ``{attribute: unit}`` of one class page (own and inherited attributes)."""
    title = _TITLE.search(text)
    if title is None:
        raise ValueError("page without <h1> class name")
    name = re.sub(r"<[^>]+>", "", title.group(1)).strip()
    headings = list(_PROPERTY.finditer(text))
    units = {}
    for i, heading in enumerate(headings):
        end = headings[i + 1].start() if i + 1 < len(headings) else len(text)
        unit = _UNIT.search(text, heading.end(), end)
        if unit:
            value = html.unescape(unit.group(1)).strip()
            if "�" in value and value not in REPAIRS:
                raise ValueError(f"{name}.{heading.group(1)}: unit {value!r} has a lost character, add it to REPAIRS")
            units[heading.group(1)] = REPAIRS.get(value, value)
    return name, units


def extract(zip_path: Path) -> dict:
    data = zip_path.read_bytes()
    units: dict[str, dict[str, str]] = {}
    with zipfile.ZipFile(zip_path) as archive:
        for member in sorted(archive.namelist()):
            parts = member.split("/")
            if len(parts) != 3 or parts[1] not in PACKAGES or not parts[2].endswith(".html"):
                continue
            if parts[2].startswith("package-"):
                continue
            name, found = page_units(decode(archive.read(member)))
            if not found:
                continue
            if name in units and units[name] != found:
                raise ValueError(f"{name} appears twice with different units: {units[name]} / {found}")
            units[name] = found
    return {
        "source": {
            "repository": "https://gitlab.opencode.de/xleitstelle/xwaermeplan/spezifikation",
            "file": "objektartenkatalog/" + zip_path.name,
            "git_blob": git_blob(data),
            "packages": list(PACKAGES),
        },
        "units": {name: dict(sorted(found.items())) for name, found in sorted(units.items())},
    }


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("catalogue", type=Path, help="XWaermeplan096.zip from the spezifikation repository")
    parser.add_argument("output", type=Path, help="JSON file to write")
    args = parser.parse_args(argv)
    result = extract(args.catalogue)
    with open(args.output, "w", encoding="utf-8", newline="\n") as f:
        json.dump(result, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"{sum(map(len, result['units'].values()))} units of {len(result['units'])} classes -> {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
